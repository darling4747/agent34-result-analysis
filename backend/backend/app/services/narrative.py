"""Narrative generation service - Gemini AI or deterministic fallback."""
from __future__ import annotations
import json
import logging
from ..config import Settings

logger = logging.getLogger(__name__)


class NarrativeService:
    """
    Generates analytical narrative from VERIFIED metrics only.
    Uses Gemini when LLM_PROVIDER=gemini and LLM_API_KEY is set.
    Falls back to deterministic templates if Gemini is unavailable.
    """

    def __init__(self, settings: Settings):
        self.settings = settings

    def generate(self, metrics: dict) -> dict:
        """Returns: summary, key_findings, recommendations, disclaimer, model_used."""
        provider = self.settings.LLM_PROVIDER.lower() if self.settings.LLM_PROVIDER else ''
        if self.settings.LLM_API_KEY and provider == 'gemini':
            try:
                return self._gemini_narrative(metrics)
            except Exception as exc:
                logger.warning('Gemini narrative failed, using deterministic fallback: %s', exc)
        elif self.settings.LLM_API_KEY and provider == 'openai':
            try:
                return self._openai_narrative(metrics)
            except Exception as exc:
                logger.warning('OpenAI narrative failed, using deterministic fallback: %s', exc)
        return self._deterministic_narrative(metrics)

    # ──────────────────────────────────────────────────────────────────
    # Gemini integration
    # ──────────────────────────────────────────────────────────────────

    def _gemini_narrative(self, metrics: dict) -> dict:
        """Call Gemini with verified metrics only. Model calculates no numbers."""
        import google.generativeai as genai  # noqa: PLC0415

        genai.configure(api_key=self.settings.LLM_API_KEY)
        model_name = self.settings.LLM_MODEL or 'gemini-3.6-flash'
        model = genai.GenerativeModel(
            model_name=model_name,
            generation_config=genai.GenerationConfig(
                temperature=0.2,
                max_output_tokens=1200,
            ),
        )

        system_instructions = (
            'You are an academic data analyst assistant for an Indian university result analysis system. '
            'You receive PRE-COMPUTED verified metrics. Your role is ONLY to generate explanatory narrative. '
            'STRICT RULES: '
            '1. Do NOT recalculate any number. Use only the metrics provided. '
            '2. Do NOT name or rank individual faculty members. '
            '3. Do NOT name individual students. '
            '4. Use cautious language: "may indicate", "warrants review", "appears to". '
            '5. Correlation does not imply causation - state this where relevant. '
            '6. Intervention priorities are recommendations for review, not accusations. '
            'Respond ONLY with valid JSON: {"summary": "...", "key_findings": [...], "recommendations": [...]}. '
            'Be concise. Target academic administrators as the audience.'
        )

        user_prompt = (
            'Generate an analytical narrative for the following verified academic result metrics. '
            'Do not alter any numerical values.\n\n'
            + json.dumps(metrics, indent=2, default=str)
        )

        full_prompt = f'{system_instructions}\n\n{user_prompt}'
        response = model.generate_content(full_prompt, request_options={'timeout': 10.0})
        raw = response.text.strip() if response.text else ""
        if not raw:
            raise ValueError("Gemini returned empty response")
        # Handle triple-backtick fences: `json\n{...}\n`
        if "`" in raw:
            parts = raw.split("`")
            raw = parts[1] if len(parts) >= 2 else raw
            if raw.startswith("json"):
                raw = raw[4:]
            raw = raw.strip()
        # Handle single-backtick wrapping: {...}
        elif raw.startswith("") and raw.endswith(""):
            raw = raw[1:-1].strip()
        # Locate the JSON object if still not at start
        if not raw.startswith("{"):
            s_idx = raw.find("{")
            e_idx = raw.rfind("}")
            if s_idx != -1 and e_idx != -1:
                raw = raw[s_idx:e_idx + 1]
        parsed = json.loads(raw)
        return {
            'summary': str(parsed.get('summary', '')),
            'key_findings': list(parsed.get('key_findings', [])),
            'recommendations': list(parsed.get('recommendations', [])),
            'disclaimer': (
                'This narrative was generated by Gemini AI from verified institutional metrics only. '
                'It is an AI-generated DRAFT and requires human review before any official use. '
                'No numerical values were modified by the AI.'
            ),
            'model_used': f'gemini/{model_name}',
        }

    # ──────────────────────────────────────────────────────────────────
    # OpenAI integration (kept for compatibility)
    # ──────────────────────────────────────────────────────────────────

    def _openai_narrative(self, metrics: dict) -> dict:
        import urllib.request  # noqa: PLC0415
        model = self.settings.LLM_MODEL or 'gpt-4o-mini'
        payload = json.dumps({
            'model': model,
            'messages': [
                {'role': 'system', 'content': 'You are an academic analyst. Never invent statistics. Respond with JSON: {summary, key_findings, recommendations}.'},
                {'role': 'user', 'content': json.dumps(metrics, default=str)},
            ],
            'max_tokens': 800, 'temperature': 0.2,
        }).encode('utf-8')
        req = urllib.request.Request(
            'https://api.openai.com/v1/chat/completions', data=payload,
            headers={'Authorization': f'Bearer {self.settings.LLM_API_KEY}', 'Content-Type': 'application/json'},
            method='POST',
        )
        with urllib.request.urlopen(req, timeout=20) as resp:
            result = json.loads(resp.read().decode('utf-8'))
            response_text = result['choices'][0]['message']['content']
        parsed = json.loads(response_text)
        return {
            'summary': parsed.get('summary', ''),
            'key_findings': parsed.get('key_findings', []),
            'recommendations': parsed.get('recommendations', []),
            'disclaimer': 'AI-generated draft. Human review required.',
            'model_used': f'openai/{model}',
        }

    # ──────────────────────────────────────────────────────────────────
    # Deterministic fallback
    # ──────────────────────────────────────────────────────────────────

    def _deterministic_narrative(self, metrics: dict) -> dict:
        """Template-based narrative from verified metrics. No external calls."""
        s = metrics.get('summary', {})
        pass_pct  = s.get('pass_percentage', 0.0) or 0.0
        fail_pct  = s.get('failure_percentage', 0.0) or 0.0
        total_stu = s.get('total_students', 0) or 0
        avg_marks = s.get('average_marks')
        avg_gpa   = s.get('average_gpa')
        prev_pass = s.get('previous_pass_percentage')
        period    = metrics.get('period', 'the current period')

        summary = (
            f'During {period}, {total_stu} students were assessed. '
            f'The overall pass rate was {pass_pct:.1f}% with a failure rate of {fail_pct:.1f}%.'
        )
        if avg_marks is not None:
            summary += f' Average total marks: {avg_marks:.1f}.'
        if avg_gpa is not None:
            summary += f' Average GPA: {avg_gpa:.2f}.'

        findings: list[str] = []
        if prev_pass is not None:
            diff = pass_pct - prev_pass
            d = 'increased' if diff >= 0 else 'decreased'
            findings.append(f'Pass rate {d} by {abs(diff):.1f} pp compared to the previous period.')

        interventions = metrics.get('interventions', []) or []
        crit = [i['course_code'] for i in interventions if i.get('priority_level') == 'CRITICAL']
        high = [i['course_code'] for i in interventions if i.get('priority_level') == 'HIGH']
        if crit:
            findings.append(f'CRITICAL priority courses requiring immediate review: {", ".join(crit)}.')
        if high:
            findings.append(f'HIGH priority courses: {", ".join(high)}.')

        corr_neg = [c['course_code'] for c in metrics.get('correlation', []) or [] if 'NEGATIVE_CORRELATION' in (c.get('flags') or [])]
        if corr_neg:
            findings.append(f'Negative internal-external correlation in: {", ".join(corr_neg)}. Assessment alignment warrants review.')

        if fail_pct > 30:
            findings.append(f'Overall failure rate ({fail_pct:.1f}%) exceeds 30% and requires institutional attention.')

        if not findings:
            findings.append(f'All metrics are within expected ranges. Pass rate: {pass_pct:.1f}%.')

        recs: list[str] = []
        if interventions:
            for item in interventions[:5]:
                ccode = item.get("course_code", "")
                cname = item.get("course_name", "")
                plevel = item.get("priority_level", "LOW")
                frate = item.get("failure_rate", 0.0)
                reasons = item.get("reasons", [])
                reason_str = f" ({reasons[0]})" if reasons else ""
                recs.append(f"[{plevel}] {ccode} - {cname}: Conduct target review and remedial support{reason_str}. Failure rate: {frate:.1f}%.")

        if crit:
            recs.append(f"Initiate immediate intensive remedial programmes for critical-priority courses: {', '.join(crit)}.")
        if high:
            recs.append(f"Schedule structured academic committee reviews for high-priority courses: {', '.join(high)}.")

        recs.append("Review internal vs external mark trends across all courses to identify assessment alignment gaps.")
        recs.append("Transmit backlog student roster to Agent 35 (Backlog Tracking Agent) for early student mentoring.")
        recs.append("Forward course-level pass percentage and SGPA distributions to Agent 8 (Attainment Agent) for OBE outcome evaluation.")

        return {
            'summary': summary.strip(),
            'key_findings': findings,
            'recommendations': recs,
            'disclaimer': (
                'This narrative was generated deterministically from verified institutional data. '
                'It should be reviewed by qualified academic staff before use.'
            ),
            'model_used': 'deterministic',
        }